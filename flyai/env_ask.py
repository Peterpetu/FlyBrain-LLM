"""Ask-to-learn environment for expected-free-energy decoding (AIF-H5).

Vocabulary: 16 keys, 16 values, '?' (ask), '=' (answer marker), '.' (filler), '>' (query marker).
Episode transcript:  [k v]*m  '>' q  ( '?' v_q )?  '=' answer
 * If the agent emits '?', the environment reveals v_q (the true value) before the answer.
 * Reward for evaluation: +1 for a correct answer, -cost for asking.

Training transcripts are generated by a *random* asking policy (ask with p_ask regardless
of whether q was shown), and the answer is always the true value. Thus the training data
contains no information about WHEN to ask; a decoder that asks when its own latent state
is uncertain (epistemic value) must discover that from the model's beliefs, not the data.
"""
from __future__ import annotations

import numpy as np
import torch

NK = 16
KEY, VAL = np.arange(0, NK), np.arange(NK, 2 * NK)
ASK, EQ, FILL, QRY = 2 * NK, 2 * NK + 1, 2 * NK + 2, 2 * NK + 3
VOCAB = 2 * NK + 4


def transcript_batch(batch: int, rng: np.random.Generator, m_pairs: int = 6, p_ask: float = 0.5, p_known: float = 0.5, T: int = 24):
    x = np.full((batch, T), FILL, dtype=np.int64); known = np.zeros(batch, bool); asked = np.zeros(batch, bool)
    for b in range(batch):
        ks = rng.choice(KEY, size=m_pairs, replace=False); vs = rng.choice(VAL, size=m_pairs)
        seq = []
        for k, v in zip(ks, vs): seq += [k, v]
        if rng.random() < p_known:
            i = rng.integers(0, m_pairs); q, vq = ks[i], vs[i]; known[b] = True
        else:
            q = rng.choice(np.setdiff1d(KEY, ks)); vq = rng.choice(VAL)
        seq += [QRY, q]
        if rng.random() < p_ask:
            seq += [ASK, vq]; asked[b] = True
        seq += [EQ, vq]
        x[b, :len(seq)] = seq[:T]
    return torch.from_numpy(x), torch.from_numpy(known), torch.from_numpy(asked)


@torch.no_grad()
def simulate(model, decide_fn, batch: int, rng: np.random.Generator, m_pairs: int = 6, p_known: float = 0.5, ask_cost: float = 0.3):
    """Roll out episodes with a decoding policy. decide_fn(model, state, allowed) -> token.
    Returns dict with accuracy, ask rate (known / unknown), and mean reward."""
    model.eval(); B = batch
    x, known, _ = transcript_batch(B, rng, m_pairs, p_ask=0.0, p_known=p_known)
    # prefix up to and including the query key
    pre_len = 2 * m_pairs + 2
    st = model.init_state(B, model.emb.weight)
    for t in range(pre_len):
        _, st, _ = model.step(st, x[:, t])
    # true value: for known, the value paired with q; for unknown, x[:, pre_len+1] holds it only if asked... recompute
    truth = x[:, pre_len + 1]                    # transcript_batch writes '=' vq at pre_len, pre_len+1 when p_ask = 0
    ask_tok = decide_fn(model, st, torch.tensor([ASK, EQ]))
    asked = ask_tok == ASK
    correct = torch.zeros(B, dtype=torch.bool)
    for b in range(B):
        stb = _slice_state(st, b)
        if asked[b]:
            _, stb, _ = model.step(stb, torch.tensor([ASK])); _, stb, _ = model.step(stb, truth[b:b + 1])
        _, stb, _ = model.step(stb, torch.tensor([EQ]))
        mu, _, _, _, _ = model._priors(stb)                    # prediction for the answer position, before observing it
        logits = model.out(model.out_norm(mu))
        ans = logits[0, NK:2 * NK].argmax() + NK
        correct[b] = ans == truth[b]
    acc = correct.float().mean().item(); asks_known = asked[known].float().mean().item() if known.any() else float("nan")
    asks_unknown = asked[~known].float().mean().item() if (~known).any() else float("nan")
    reward = (correct.float() - ask_cost * asked.float()).mean().item()
    model.train()
    return {"acc": acc, "ask_rate_known": asks_known, "ask_rate_unknown": asks_unknown, "reward": reward, "acc_known": correct[known].float().mean().item(), "acc_unknown": correct[~known].float().mean().item()}


def _slice_state(st, b):
    """Recursively take batch element b of a nested state (dicts / tuples / lists / tensors / scalars)."""
    if torch.is_tensor(st): return st[b:b + 1] if st.dim() > 0 else st
    if isinstance(st, dict): return {k: _slice_state(v, b) for k, v in st.items()}
    if isinstance(st, tuple): return tuple(_slice_state(v, b) for v in st)
    if isinstance(st, list): return [_slice_state(v, b) for v in st]
    return st
